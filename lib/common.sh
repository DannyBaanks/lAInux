# shellcheck shell=bash
# ==============================================================================
# Shared helpers for every app recipe in the corpus (apps/<app>/transmute.sh).
#
# POLICY (same for every app):
# - No upstream binary is tracked in git; each one is fetched by the user from
#   its official source or supplied from the user's own download.
# - Every upstream input is pinned by SHA-256 and the pipeline fails closed.
# - The user's profile (~/.config/<App>) is never modified or removed.
# ==============================================================================

CORPUS_ROOT="${CORPUS_ROOT:-$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)}"
CORPUS_CACHE="${CORPUS_CACHE:-${XDG_CACHE_HOME:-$HOME/.cache}/lainux}"

_c_g="\033[0;32m"; _c_b="\033[0;34m"; _c_y="\033[1;33m"; _c_r="\033[0;31m"; _c_0="\033[0m"
log_info() { echo -e "${_c_b}[INFO]${_c_0} $*"; }
log_ok()   { echo -e "${_c_g}[✓]${_c_0} $*"; }
log_warn() { echo -e "${_c_y}[!]${_c_0} $*"; }
log_err()  { echo -e "${_c_r}[ERROR]${_c_0} $*" >&2; }

# verify_sha256 FILE EXPECTED -> 0 when it matches, 1 (with a report) otherwise.
verify_sha256() {
    local file="$1" want="$2" got
    got=$(sha256sum "$file" | awk '{print $1}')
    if [[ "$got" != "$want" ]]; then
        log_err "SHA-256 mismatch for $(basename "$file")"
        log_err "  expected: $want"
        log_err "  observed: $got"
        log_err "FAIL CLOSED: upstream drift or a corrupted download."
        return 1
    fi
    log_ok "SHA-256 verified: $(basename "$file") ($got)"
}

# fetch_pinned URL SHA256 NAME -> prints the path of a verified copy in the cache.
# A cached copy is reused only when its hash still matches.
fetch_pinned() {
    local url="$1" sha="$2" name="$3" out
    mkdir -p "$CORPUS_CACHE"
    out="$CORPUS_CACHE/$name"
    if [[ -f "$out" ]] && verify_sha256 "$out" "$sha" >/dev/null 2>&1; then
        log_info "Using verified cached $name" >&2
        printf '%s\n' "$out"
        return 0
    fi
    log_info "Downloading $url" >&2
    curl -fL --progress-bar -o "$out.part" "$url" >&2
    if ! verify_sha256 "$out.part" "$sha" >&2; then
        rm -f "$out.part"
        return 1
    fi
    mv -f "$out.part" "$out"
    printf '%s\n' "$out"
}

# require_cmds CMD... -> fails naming every missing command.
require_cmds() {
    local missing=()
    for c in "$@"; do command -v "$c" >/dev/null 2>&1 || missing+=("$c"); done
    if (( ${#missing[@]} )); then
        log_err "Missing required commands: ${missing[*]}"
        return 1
    fi
}

# find_download GLOB -> first match in the usual download folders.
find_download() {
    local glob="$1" d hit
    for d in "${XDG_DOWNLOAD_DIR:-}" "$HOME/Descargas" "$HOME/Downloads" "$HOME"; do
        [[ -n "$d" && -d "$d" ]] || continue
        hit=$(find "$d" -maxdepth 2 -type f -iname "$glob" 2>/dev/null | sort | tail -n 1)
        if [[ -n "$hit" ]]; then printf '%s\n' "$hit"; return 0; fi
    done
    return 1
}

# write_launcher PATH INSTALL_DIR EXECUTABLE TITLE
write_launcher() {
    local path="$1" dir="$2" exe="$3" title="$4"
    mkdir -p "$(dirname "$path")"
    cat > "$path" <<EOF
#!/usr/bin/env bash
# $title - native Linux launcher (generated by lainux)
# --no-sandbox: Ubuntu 24.04+ restricts unprivileged user namespaces
# (kernel.apparmor_restrict_unprivileged_userns=1) unless an AppArmor profile
# for this binary is installed.
exec "$dir/$exe" --no-sandbox "\$@"
EOF
    chmod +x "$path"
    log_ok "Launcher: $path"
}

# write_desktop_entry PATH NAME COMMENT LAUNCHER ICON WMCLASS SCHEME CATEGORIES
write_desktop_entry() {
    local path="$1" name="$2" comment="$3" launcher="$4" icon="$5" wmclass="$6" scheme="$7" cats="$8"
    mkdir -p "$(dirname "$path")"
    cat > "$path" <<EOF
[Desktop Entry]
Name=$name
Comment=$comment
Exec=$launcher %U
Icon=$icon
Terminal=false
Type=Application
Categories=$cats
MimeType=x-scheme-handler/$scheme;
StartupWMClass=$wmclass
EOF
    if command -v update-desktop-database >/dev/null 2>&1; then
        update-desktop-database "$(dirname "$path")" 2>/dev/null || true
    fi
    log_ok "Desktop entry: $path"
}
